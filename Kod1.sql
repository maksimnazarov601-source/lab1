-- Первая таблица: Лаборатории
CREATE TABLE laboratorii (
    nomer_laboratorii INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazvanie VARCHAR(100) NOT NULL,
    rod_deyatelnosti VARCHAR(200) NOT NULL,
    zaveduyushchiy VARCHAR(100),
    kolichestvo_rabochih_mest INTEGER NOT NULL,
    proektnoe_oborudovanie BOOLEAN NOT NULL,
    nomer_kafedry INTEGER NOT NULL
);
